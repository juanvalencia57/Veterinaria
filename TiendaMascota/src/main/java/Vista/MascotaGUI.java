    private Integer parseIntOrWarn(javax.swing.JTextField field, String label) {
    String v = field.getText() == null ? "" : field.getText().trim();
    if (v.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this,
                label + " no puede estar vacío.",
                "Datos incorrectos",
                javax.swing.JOptionPane.ERROR_MESSAGE);
        field.requestFocus();
        return null;
    }
    try {
        return Integer.parseInt(v);
    } catch (NumberFormatException ex) {
        javax.swing.JOptionPane.showMessageDialog(this,
                label + " debe ser un número entero.",
                "Datos incorrectos",
                javax.swing.JOptionPane.ERROR_MESSAGE);
        field.requestFocus();
        return null;
    }
}

private Double parseDoubleOrWarn(javax.swing.JTextField field, String label) {
    String v = field.getText() == null ? "" : field.getText().trim();
    if (v.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this,
                label + " no puede estar vacío.",
                "Datos incorrectos",
                javax.swing.JOptionPane.ERROR_MESSAGE);
        field.requestFocus();
        return null;
    }
    try {
        return Double.parseDouble(v);
    } catch (NumberFormatException ex) {
        javax.swing.JOptionPane.showMessageDialog(this,
                label + " debe ser un número.",
                "Datos incorrectos",
                javax.swing.JOptionPane.ERROR_MESSAGE);
        field.requestFocus();
        return null;
    }
}
private boolean camposObligatoriosLlenos() {
    // Campos obligatorios en agregar / actualizar
    String n = nombre.getText().trim();
    String r = raza.getText().trim();
    String e = edad.getText().trim();
    String t = tipo.getText().trim();
    String i = id.getText().trim();
    String p = peso.getText().trim();
    String f = ingreso.getText().trim();
    String o = origen.getText().trim();
    String g = genero.getText().trim();
    String pr = precio.getText().trim();

    // Opción simple: si cualquiera está vacío -> mensaje general
    if (n.isEmpty() || r.isEmpty() || e.isEmpty() || t.isEmpty() || i.isEmpty()
            || p.isEmpty() || f.isEmpty() || o.isEmpty() || g.isEmpty() || pr.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this,
                "Debe llenar todos los datos.",
                "Datos incompletos",
                javax.swing.JOptionPane.ERROR_MESSAGE);
        return false;
    }

    return true;
    
}
