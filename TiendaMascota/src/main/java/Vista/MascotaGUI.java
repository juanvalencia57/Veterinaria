    private void botonAceptarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_botonAceptarActionPerformed
        switch (opcion.getSelectedItem().toString()) {
        case "Agregar mascota": {
            // Verificación previa de todos los campos (texto + numéricos)
            if (!camposObligatoriosLlenos()) return;

            Integer edadVal = parseIntOrWarn(edad, "Edad");
            Double pesoVal = parseDoubleOrWarn(peso, "Peso");
            Double precioVal = parseDoubleOrWarn(precio, "Precio");
            if (edadVal == null || pesoVal == null || precioVal == null) return;

            control.almacenarMascota(
                nombre.getText().trim().toUpperCase(),
                raza.getText().trim().toUpperCase(),
                edadVal,
                tipo.getText().trim().toUpperCase(),
                id.getText().trim(),
                pesoVal,
                ingreso.getText().trim(),
                origen.getText().trim().toUpperCase(),
                genero.getText().trim().toUpperCase(),
                precioVal
            );
            break;
        }
        case "Consultar mascota":
            control.consultarMascota(id.getText().trim());
            break;

        case "Actualizar mascota": {
            if (!camposObligatoriosLlenos()) return;

            Integer edadVal = parseIntOrWarn(edad, "Edad");
            Double pesoVal = parseDoubleOrWarn(peso, "Peso");
            Double precioVal = parseDoubleOrWarn(precio, "Precio");
            if (edadVal == null || pesoVal == null || precioVal == null) return;

            control.actualizarMascota(
                nombre.getText().trim().toUpperCase(),
                raza.getText().trim().toUpperCase(),
                edadVal,
                tipo.getText().trim().toUpperCase(),
                id.getText().trim(),
                pesoVal,
                ingreso.getText().trim(),
                origen.getText().trim().toUpperCase(),
                genero.getText().trim().toUpperCase(),
                precioVal
            );
            break;
        }
        case "Listar mascotas":
            control.listarMascotas();
            break;
        case "Eliminar mascota":
            control.eliminarMascota(id.getText().trim());
            break;
        case "Gestionar vacunas":
            // Ya lo manejas en opcionActionPerformed
            break;
    }
    }//GEN-LAST:event_botonAceptarActionPerformed
