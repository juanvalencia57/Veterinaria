public void activarTodo() {
        labelIdentificacion.setEnabled(true);
        identificacion.setEnabled(true);
        labelNombre.setEnabled(true);
        nombre.setEnabled(true);
        labelTipo.setEnabled(true);
        tipo.setEnabled(true);
        labelPrecio.setEnabled(true);
        precio.setEnabled(true);
        labelCantidad.setEnabled(true);
        cantidad.setEnabled(true);
    }

    public void activarSoloDocumento() {
        labelIdentificacion.setEnabled(true);
        identificacion.setEnabled(true);
        labelNombre.setEnabled(false);
        nombre.setEnabled(false);
        labelTipo.setEnabled(false);
        tipo.setEnabled(false);
        labelPrecio.setEnabled(false);
        precio.setEnabled(false);
        labelCantidad.setEnabled(false);
        cantidad.setEnabled(false);
    }
