    private void botonAceptarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_botonAceptarActionPerformed
        switch (opcion.getSelectedItem().toString()) {
            case "Agregar accesorio":
                control.almacenarAccesorio(
                    identificacion.getText().trim().toUpperCase(),
                    nombre.getText().trim().toUpperCase(),
                    tipo.getText().trim().toUpperCase(),
                    precio.getText().trim(),
                    cantidad.getText().trim()
                );
                break;
            case "Consultar accesorio":
                control.consultarAccesorio(identificacion.getText().trim());
                break;
            case "Actualizar accesorio":
                control.actualizarAccesorio(
                    identificacion.getText().trim().toUpperCase(),
                    nombre.getText().trim().toUpperCase(),
                    tipo.getText().trim().toUpperCase(),
                    precio.getText().trim(),
                    cantidad.getText().trim()
                );
                break;
            case "Listar accesorios":
                control.listarAccesorios();
                break;
            case "Eliminar accesorio":
                control.eliminarAccesorio(identificacion.getText().trim());
                break;
        }
    }//GEN-LAST:event_botonAceptarActionPerformed

