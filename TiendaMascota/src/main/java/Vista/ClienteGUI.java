    private void opcionActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_opcionActionPerformed
        switch (opcion.getSelectedItem().toString()) {
            case "Agregar cliente":
            activarTodo();
            break;
            case "Consultar cliente":
            activarSoloDocumento();
            break;
            case "Actualizar cliente":
            activarTodo();
            break;
            case "Listar clientes":
            activarSoloDocumento();
            labelIdentificacion.setEnabled(false);
            identificacion.setEnabled(false);
            break;
            case "Eliminar cliente":
            activarSoloDocumento();
            break;
        }
    }//GEN-LAST:event_opcionActionPerformed
public void activarTodo() {
        labelIdentificacion.setEnabled(true);
        identificacion.setEnabled(true);
        labelNombres.setEnabled(true);
        nombres.setEnabled(true);
        labelDireccion.setEnabled(true);
        direccion.setEnabled(true);
        labelNumero.setEnabled(true);
        numero.setEnabled(true);
    }

    public void activarSoloDocumento() {
        labelIdentificacion.setEnabled(true);
        identificacion.setEnabled(true);
        labelNombres.setEnabled(false);
        nombres.setEnabled(false);
        labelDireccion.setEnabled(false);
        direccion.setEnabled(false);
        labelNumero.setEnabled(false);
        numero.setEnabled(false);
    }
