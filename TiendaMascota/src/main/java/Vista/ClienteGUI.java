    private void botonAceptarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_botonAceptarActionPerformed
        switch (opcion.getSelectedItem().toString()) {
            case "Agregar cliente":
            control.almacenarCliente(
                identificacion.getText().trim().toUpperCase(),
                nombres.getText().trim().toUpperCase(),
                direccion.getText().trim().toUpperCase(),
                numero.getText().trim()
            );
            break;
            case "Consultar cliente":
            control.consultarCliente(identificacion.getText().trim());
            break;
            case "Actualizar cliente":
            control.actualizarCliente(
                identificacion.getText().trim().toUpperCase(),
                nombres.getText().trim().toUpperCase(),
                direccion.getText().trim().toUpperCase(),
                numero.getText().trim()
            );
            break;
            case "Listar clientes":
            control.listarClientes();
            break;
            case "Eliminar cliente":
            control.eliminarCliente(identificacion.getText().trim());
            break;
        }
    }//GEN-LAST:event_botonAceptarActionPerformed

