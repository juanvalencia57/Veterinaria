    private void botonAceptarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_botonAceptarActionPerformed
                                                
        String id = idmascota.getText().trim();
        String fechaStr = fecha.getText().trim();
        String sintomasStr = sintomas.getText().trim();
        String tratamientoStr = tratamiento.getText().trim();

        switch (opcion.getSelectedItem().toString()) {
            case "Agregar consulta":
                control.registrarConsulta(id, fechaStr, sintomasStr, tratamientoStr);
                break;

            case "Consultar consulta":
                control.consultarConsulta(id);
                break;

            case "Actualizar consulta":
                control.actualizarConsulta(id, fechaStr, sintomasStr, tratamientoStr);
                break;

            case "Eliminar consulta":
                control.eliminarConsulta(id, fechaStr);
                break;

            case "Listar consultas":
                control.listarConsultas();
                break;
        } 

    }//GEN-LAST:event_botonAceptarActionPerformed

