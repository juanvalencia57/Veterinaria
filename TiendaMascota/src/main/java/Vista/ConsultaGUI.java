    private void opcionActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_opcionActionPerformed
        switch (opcion.getSelectedItem().toString()) {
            case "Agregar consulta":
                activarTodo();
                break;
            case "Consultar consulta":
                activarSoloId();
                break;
            case "Actualizar consulta":
                activarTodo();
                break;
            case "Listar consultas":
                desactivarCampos();
                break;
            case "Eliminar consulta":
                activarSoloIdYFecha();
                break;
        }
    }//GEN-LAST:event_opcionActionPerformed

